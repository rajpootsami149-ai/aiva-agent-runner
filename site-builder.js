import { Daytona } from "@daytona/sdk";
import { streamSSE } from "hono/streaming";

const MODEL_URL = "https://api.xkiro.com/v1/chat/completions";
const DEFAULT_MODEL = "mistralai/mistral-large-4-0";

function plainText(value) {
  if (typeof value === "string") return value;
  if (Array.isArray(value)) return value.filter(p => p?.type === "text").map(p => p.text || "").join("");
  return "";
}
function decodeJSONFromModel(raw) {
  const clean = String(raw).trim().replace(/^```(?:json)?\s*/i, "").replace(/\s*```$/, "");
  const start = clean.indexOf("{");
  const end = clean.lastIndexOf("}");
  if (start < 0 || end <= start) throw new Error("xKiro did not return JSON website files");
  return JSON.parse(clean.slice(start, end + 1));
}
function sanitizeFiles(response) {
  let files = response?.files;
  if (Array.isArray(files)) {
    files = Object.fromEntries(files.map(f => [f?.name, f?.content]));
  }
  if (!files || typeof files !== "object") throw new Error("Invalid website files response");
  const keys = Object.keys(files);
  if (!keys.includes("index.html") || keys.length > 4) throw new Error("index.html is required, maximum 4 files");
  for (const name of keys) {
    if (!["index.html", "styles.css", "app.js", "README.txt"].includes(name)) throw new Error("Unexpected generated file: " + name.slice(0, 30));
    if (typeof files[name] !== "string" || files[name].length > 42000) throw new Error("Invalid or oversized file: " + name);
  }
  // The builder accepts these exact three static website assets.
  if (!files["styles.css"]) files["styles.css"] = ":root{color-scheme:dark;font-family:system-ui}body{margin:0}";
  if (!files["app.js"]) files["app.js"] = "// Generated by AIVA\n";
  if (!/<!doctype\s+html/i.test(files["index.html"])) throw new Error("Generated HTML is missing doctype");
  if (!/name\s*=\s*["']viewport["']/i.test(files["index.html"])) throw new Error("Generated HTML lacks mobile viewport");
  if (!/styles\.css/i.test(files["index.html"])) throw new Error("HTML must reference styles.css");
  if (!/app\.js/i.test(files["index.html"])) throw new Error("HTML must reference app.js");
  const total = Object.values(files).reduce((n, value) => n + value.length, 0);
  if (total > 85000) throw new Error("Website source exceeds build limit");
  files["README.txt"] = "Generated by AIVA AI with xKiro, tested and zipped in a Daytona sandbox. Review generated HTML/JS before publishing.\n";
  return files;
}
function toBase64(text) {
  const bytes = new TextEncoder().encode(text);
  let binary = "";
  for (let i = 0; i < bytes.length; i++) binary += String.fromCharCode(bytes[i]);
  return btoa(binary);
}
function makePython(files) {
  const payload = toBase64(JSON.stringify(files));
  return `import base64,io,json,pathlib,zipfile\nfiles=json.loads(base64.b64decode('${payload}').decode('utf-8'))\nroot=pathlib.Path('/tmp/aiva_project')\nroot.mkdir(parents=True,exist_ok=True)\nfor name,content in files.items():\n    (root/name).write_text(content,encoding='utf-8')\nassert '<!doctype' in files['index.html'].lower()\nassert 'styles.css' in files['index.html']\nassert 'app.js' in files['index.html']\narchive=io.BytesIO()\nwith zipfile.ZipFile(archive,'w',zipfile.ZIP_DEFLATED) as z:\n    for name in files: z.write(root/name,arcname=name)\narchive.seek(0)\nwith zipfile.ZipFile(archive) as z:\n    assert z.testzip() is None\n    assert sorted(z.namelist()) == sorted(files)\nprint('AIVA_ZIP_CHECK_OK')\nprint('AIVA_ZIP='+base64.b64encode(archive.getvalue()).decode('ascii'))`;
}
async function requestFiles(env, prompt, model, signal) {
  const response = await fetch(MODEL_URL, {
    method: "POST",
    headers: {"Authorization":"Bearer " + env.XKIRO_API_KEY, "Content-Type":"application/json"},
    body: JSON.stringify({
      model, stream:false, max_tokens:5500,
      messages: [
        {role:"system",content:"You are a professional front-end developer. Return only a valid JSON object containing a `files` object with EXACT keys index.html, styles.css, app.js, each containing complete source as a string. The HTML must include <!doctype html>, mobile viewport meta, stylesheet link to styles.css, script src app.js. Build a beautiful, accessible, responsive modern static site, no outside dependencies, no external scripts, no CDN, no network code, working interactive button where appropriate. Be concise to fit response. No markdown fences."},
        {role:"user",content:prompt}
      ]
    }),
    signal:AbortSignal.any([signal,AbortSignal.timeout(100000)])
  });
  if(!response.ok) {
    await response.body?.cancel();
    throw new Error(`xKiro website generator HTTP ${response.status}`);
  }
  const data=await response.json();
  const raw=plainText(data?.choices?.[0]?.message?.content);
  return sanitizeFiles(decodeJSONFromModel(raw));
}

export async function buildWebsite(c) {
  if (c.env.AIVA_ENABLE_DAYTONA_TOOLS !== "yes") return c.json({error:"Agent builder disabled"},503);
  if (!c.env.XKIRO_API_KEY || !c.env.DAYTONA_API_KEY) return c.json({error:"Agent keys are not configured"},503);
  const input = await c.req.json().catch(() => ({}));
  const prompt=typeof input.prompt === "string" ? input.prompt.trim().slice(0,2000) : "";
  if (prompt.length < 8) return c.json({error:"Provide a website request of at least 8 characters"},400);
  const model = typeof input.model === "string" && /^[a-zA-Z0-9._/-]{3,120}$/.test(input.model)
    ? input.model : DEFAULT_MODEL;
  const threadId=crypto.randomUUID(),runId=crypto.randomUUID();
  c.header("Cache-Control","no-cache, no-transform");
  return streamSSE(c, async stream => {
    const send = data => stream.writeSSE({data:JSON.stringify(data)});
    const activity=(label,status)=>send({type:"CUSTOM",name:"aiva.activity",value:{label,status,at:new Date().toISOString()}});
    let daytona=null,sandbox=null,cleanupError=null;
    try {
      await send({type:"RUN_STARTED",threadId,runId});
      await activity("Generating website source with xKiro","started");
      const files=await requestFiles(c.env,prompt,model,c.req.raw.signal);
      await activity("Website source generated","completed");
      await activity("Creating Daytona sandbox","started");
      daytona=new Daytona({apiKey:c.env.DAYTONA_API_KEY});
      sandbox=await daytona.v2.create({waitSeconds:60});
      console.info("AIVA_DAYTONA_CREATE_OK",{runId,sandboxId:String(sandbox?.id||"").slice(0,80)});
      await activity("Daytona sandbox ready","completed");
      await activity("Writing and testing website files","started");
      const result=await sandbox.runCode(makePython(files),{timeoutSeconds:40,isolated:true});
      const output=String(result?.logs?.stdout||"");
      const match=output.match(/(?:^|\n)AIVA_ZIP=([a-zA-Z0-9+/=]+)/);
      if(result?.error || !output.includes("AIVA_ZIP_CHECK_OK") || !match){
        throw new Error("Daytona build verification failed: "+String(result?.error?.message||result?.logs?.stderr||output).slice(0,250));
      }
      const binary=atob(match[1]);
      if(binary.length>250000) throw new Error("Generated ZIP exceeds 250KB demo limit");
      await activity("Website tests and ZIP verified","completed");
      // Clean up BEFORE returning a successful artifact. A failed cleanup is reported.
      await daytona.v2.delete(sandbox);
      console.info("AIVA_DAYTONA_DELETE_OK",{runId});
      sandbox=null;
      await activity("Sandbox deleted","completed");
      await send({type:"CUSTOM",name:"aiva.artifact",value:{fileName:"aiva-generated-website.zip",mime:"application/zip",base64:match[1],bytes:binary.length}});
      const messageId=crypto.randomUUID();
      await send({type:"TEXT_MESSAGE_START",role:"assistant",messageId});
      await send({type:"TEXT_MESSAGE_CONTENT",messageId,delta:"Website source generated by xKiro and packaged in Daytona. Download your ZIP below. Tests checked file references and ZIP integrity; browser UI testing is still recommended."});
      await send({type:"TEXT_MESSAGE_END",messageId});
      await send({type:"RUN_FINISHED",threadId,runId});
    } catch(error) {
      console.error("AIVA website build error", {runId,message:String(error?.message||error).slice(0,250)});
      await activity("Website build failed","failed").catch(()=>{});
      await send({type:"RUN_ERROR",message:String(error?.message||"Build failed").slice(0,300)}).catch(()=>{});
    } finally {
      if(sandbox&&daytona){
        try{await daytona.v2.delete(sandbox);await activity("Sandbox deleted","completed");}
        catch(error){cleanupError=error;console.error("AIVA sandbox cleanup failed",{runId,message:String(error?.message||error).slice(0,250)});await activity("Sandbox cleanup failed — check Daytona dashboard","failed").catch(()=>{});}
      }
      if(daytona) await daytona.close?.().catch(()=>{});
    }
  });
}
